// Clean source badge styles with support for dark and light mode
export function getSourceBadgeStyle(source: string): {
  bg: string;
  text: string;
  border: string;
  dot: string;
} {
  const s = source.toLowerCase();
  if (s.includes("openai")) {
    return {
      bg: "bg-emerald-50 dark:bg-emerald-950/40",
      text: "text-emerald-700 dark:text-emerald-300",
      border: "border-emerald-200 dark:border-emerald-800/40",
      dot: "bg-emerald-500 dark:bg-emerald-400",
    };
  }
  if (s.includes("google")) {
    return {
      bg: "bg-blue-50 dark:bg-blue-950/40",
      text: "text-blue-700 dark:text-blue-300",
      border: "border-blue-200 dark:border-blue-800/40",
      dot: "bg-blue-500 dark:bg-blue-400",
    };
  }
  if (s.includes("techcrunch")) {
    return {
      bg: "bg-teal-50 dark:bg-teal-950/40",
      text: "text-teal-700 dark:text-teal-300",
      border: "border-teal-200 dark:border-teal-800/40",
      dot: "bg-teal-500 dark:bg-teal-400",
    };
  }
  if (s.includes("venturebeat")) {
    return {
      bg: "bg-indigo-50 dark:bg-indigo-950/40",
      text: "text-indigo-700 dark:text-indigo-300",
      border: "border-indigo-200 dark:border-indigo-800/40",
      dot: "bg-indigo-500 dark:bg-indigo-400",
    };
  }
  if (s.includes("arxiv")) {
    return {
      bg: "bg-amber-50 dark:bg-amber-950/40",
      text: "text-amber-800 dark:text-amber-300",
      border: "border-amber-200 dark:border-amber-800/40",
      dot: "bg-amber-500 dark:bg-amber-400",
    };
  }
  return {
    bg: "bg-surface2",
    text: "text-inkSecondary",
    border: "border-line",
    dot: "bg-mutedDark",
  };
}
